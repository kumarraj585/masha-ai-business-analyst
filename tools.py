# ============================================================
# TOOL 6: SPECIFIC COUNTRY REVENUE
# ============================================================

@tool
def get_country_revenue(
    country: str
) -> dict:
    """Get revenue generated by a specific country."""

    df = load_data()

    matches = df[
        df["Country"]
        .str.lower()
        .str.strip()
        == country.lower().strip()
    ]

    if matches.empty:
        return {
            "error": (
                f"Country '{country}' "
                "was not found."
            )
        }

    revenue = matches["Revenue"].sum()

    return {
        "country": country,
        "currency": "GBP",
        "revenue": round(
            float(revenue),
            2
        ),
        "transactions": int(
            matches["Invoice"].nunique()
        ),
    }


# ============================================================
# TOOL 7: TOP CUSTOMERS
# ============================================================

@tool
def get_top_customers(
    n: int = 5
) -> dict:
    """Get customers ranked by total revenue."""

    df = load_data()

    customer_data = (
        df.dropna(
            subset=["Customer ID"]
        )
    )

    result = (
        customer_data
        .groupby("Customer ID")["Revenue"]
        .sum()
        .sort_values(ascending=False)
        .head(n)
    )

    return {
        "currency": "GBP",
        "customers": {
            str(int(customer)): round(
                float(revenue),
                2
            )
            for customer, revenue in result.items()
        },
    }


# ============================================================
# TOOL 8: AVERAGE ORDER VALUE
# ============================================================

@tool
def get_average_order_value() -> dict:
    """Calculate the average revenue per invoice."""

    df = load_data()

    total_revenue = df["Revenue"].sum()

    total_transactions = (
        df["Invoice"].nunique()
    )

    aov = (
        total_revenue
        / total_transactions
    )

    return {
        "currency": "GBP",
        "average_order_value": round(
            float(aov),
            2
        ),
        "total_revenue": round(
            float(total_revenue),
            2
        ),
        "total_transactions": int(
            total_transactions
        ),
    }


# ============================================================
# TOOL 9: MONTHLY REVENUE
# ============================================================

@tool
def get_monthly_revenue() -> dict:
    """Get total revenue for each month."""

    df = load_data()

    result = (
        df.groupby(
            df["InvoiceDate"].dt.to_period("M")
        )["Revenue"]
        .sum()
        .sort_index()
    )

    return {
        str(month): round(
            float(revenue),
            2
        )
        for month, revenue in result.items()
    }


# ============================================================
# TOOL 10: BEST MONTH
# ============================================================

@tool
def get_best_month() -> dict:
    """Find the month with the highest revenue."""

    df = load_data()

    monthly = (
        df.groupby(
            df["InvoiceDate"].dt.to_period("M")
        )["Revenue"]
        .sum()
    )

    best_month = monthly.idxmax()

    return {
        "month": str(best_month),
        "currency": "GBP",
        "revenue": round(
            float(monthly.max()),
            2
        ),
    }


# ============================================================
# TOOL 11: MONTHLY REVENUE GROWTH
# ============================================================

@tool
def get_monthly_growth() -> dict:
    """Calculate month-over-month revenue growth."""

    df = load_data()

    monthly = (
        df.groupby(
            df["InvoiceDate"].dt.to_period("M")
        )["Revenue"]
        .sum()
        .sort_index()
    )

    growth = (
        monthly.pct_change()
        * 100
    )

    return {
        str(month): (
            None
            if pd.isna(value)
            else round(
                float(value),
                2
            )
        )
        for month, value in growth.items()
    }


# ============================================================
# TOOL 12: FINAL NEXT-MONTH FORECAST
# ============================================================

@tool
def get_next_month_forecast() -> dict:
    """Forecast the next calendar month's revenue.

    Uses the daily Random Forest forecasting pipeline
    trained on the full Online Retail II transaction history.

    Evaluation metrics are calculated dynamically.
    Revenue is in GBP.
    """

    # Load full transaction history
    full_df = load_full_data()

    # Convert transactions to daily revenue
    daily_revenue = get_daily_revenue(
        full_df
    )

    # Evaluate model dynamically
    (
        _,
        mae,
        rmse,
        r2
    ) = evaluate_model(
        daily_revenue
    )

    # Forecast next calendar month
    (
        forecast_df,
        month,
        total_forecast
    ) = forecast_next_month(
        daily_revenue
    )

    return {
        "forecast_month": str(month),
        "currency": "GBP",
        "predicted_revenue": round(
            float(total_forecast),
            2
        ),
        "forecasted_days": len(
            forecast_df
        ),
        "model": "Random Forest",
        "granularity": "Daily",
        "mae": round(
            float(mae),
            2
        ),
        "rmse": round(
            float(rmse),
            2
        ),
        "r2": round(
            float(r2),
            2
        ),
    }


