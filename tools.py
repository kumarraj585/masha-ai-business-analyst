import pandas as pd

from langchain.tools import tool

from daily_forecasting import (
    load_full_data,
    get_daily_revenue,
    evaluate_model,
    forecast_next_month,
)


# ============================================================
# LOAD PROJECT DATA
# ============================================================

def load_data():
    df = pd.read_csv(
        "data/online_retail.csv"
    )

    df["InvoiceDate"] = pd.to_datetime(
        df["InvoiceDate"]
    )

    df["Revenue"] = (
        df["Quantity"] * df["Price"]
    )

    return df


# ============================================================
# TOOL 1: BUSINESS SUMMARY
# ============================================================

@tool
def get_business_summary() -> dict:
    """Get the main business KPIs from the retail dataset.

    Returns actual values calculated from the project dataset.
    Revenue and prices are in GBP.
    """

    df = load_data()

    return {
        "currency": "GBP",
        "currency_symbol": "£",
        "total_revenue": round(
            float(df["Revenue"].sum()),
            2
        ),
        "total_quantity": int(
            df["Quantity"].sum()
        ),
        "unique_products": int(
            df["Description"].nunique()
        ),
        "unique_customers": int(
            df["Customer ID"].nunique()
        ),
        "unique_countries": int(
            df["Country"].nunique()
        ),
        "total_transactions": int(
            df["Invoice"].nunique()
        ),
    }


# ============================================================
# TOOL 2: TOP PRODUCTS BY REVENUE
# ============================================================

@tool
def get_top_products(
    n: int = 5
) -> dict:
    """Get the top products ranked by total revenue."""

    df = load_data()

    result = (
        df.groupby("Description")["Revenue"]
        .sum()
        .sort_values(ascending=False)
        .head(n)
    )

    return {
        "currency": "GBP",
        "products": {
            str(product): round(
                float(revenue),
                2
            )
            for product, revenue in result.items()
        },
    }


